// 미수금 관리 (DCC's own overdue-collections tracker) - one row per retailer that has
// received at least one partial payment on a charge but still owes something. Mirrors
// PayableOverdueRowDto's MFG-side convention exactly, grouped by retailer instead of by
// DCC partner.
public class ReceivableOverdueRowDto
{

    public int UserId { get; set; }

    public string? CompanyName { get; set; }

    public string? UserDisplayName { get; set; }

    // Oldest still-outstanding charge's own date - what 연체 일수 counts forward from.
    public DateTime SaleDate { get; set; }

    public decimal SaleAmount { get; set; }

    public decimal SaleWeight { get; set; }

    public decimal CollectedAmount { get; set; }

    public decimal CollectedWeight { get; set; }

    public decimal OutstandingAmount { get; set; }

    public decimal OutstandingWeight { get; set; }

    public int OverdueDays { get; set; }

    // Feeds ReceivableBatchSettleDialog's order-ids prop for the "입금처리" action.
    public List<int> OrderIds { get; set; } = new();
}

// One row per DEPOSIT that paid off a given CHARGE - lets 주문별 보기's expand show which
// transaction(s) closed out this order instead of only the flat 거래별 보기 list, mirrors
// Payable's ChargeApplicationRowDto exactly.
public class ReceivableChargeApplicationRowDto
{

    public int DepositId { get; set; }

    public decimal AppliedAmount { get; set; }

    public decimal AppliedWeight { get; set; }

    public DateTime DepositCreatedAt { get; set; }

    public bool IsCancelled { get; set; }

    public string? Memo { get; set; }

    // The deposit's OWN recorded amount/weight/discount (as opposed to AppliedAmount/
    // AppliedWeight above, which is only the portion allocated to THIS charge) - needed so
    // this row is self-sufficient for editing/cancelling the deposit directly from the
    // nested history view, without a second round-trip to fetch the full deposit record.
    public decimal Amount { get; set; }

    public decimal Weight { get; set; }

    public decimal Discount { get; set; }

    // Set when this deposit was auto-generated by a 정산처리 (Payable) payment - blocks
    // manual edit/cancel here, same rule already enforced by the API for a direct deposit.
    public int? SourcePaymentId { get; set; }
}
