namespace GoldbApi.DTOs;

public class ReceivableDto
{

    public int Id { get; set; }

    public int UserId { get; set; }

    public string? UserName { get; set; }

    public string? UserDisplayName { get; set; }

    // The retailer's own RTL company name (falls back to their first company if they have no
    // RTL membership) - mirrors UserReceivableSummaryDto.CompanyName, so 정산 완료 내역's
    // "거래처" column shows the same identity 미수금 관리 already does, not just the raw
    // user display name.
    public string? CompanyName { get; set; }

    public int? OrderId { get; set; }

    public string? OrderNo { get; set; }

    public string? ProductName { get; set; }

    public string? ProductPhotoUrl { get; set; }

    public string Type { get; set; } = string.Empty;

    public decimal Amount { get; set; }

    public decimal RemainingAmount { get; set; }

    public decimal Weight { get; set; }

    public decimal RemainingWeight { get; set; }

    public string? Memo { get; set; }

    public string? SettlementMethod { get; set; }

    public decimal Discount { get; set; }

    public bool IsCancelled { get; set; }

    public DateTime CreatedAt { get; set; }

    // Only set for a DEPOSIT auto-generated by a 정산처리 (Payable) payment - lets the
    // frontend block manual edit/cancel here and point the user to the source payment instead.
    public int? SourcePaymentId { get; set; }

    // Only populated for DEPOSIT rows - which charge(s) this payment actually paid
    // off, since a payment can spill over past its own order into other outstanding
    // charges (oldest first) once its tagged order is fully covered.
    public List<AppliedChargeDto> AppliedCharges { get; set; } = new();

    // For a DEPOSIT row: the current (as of now) unsettled RemainingAmount/RemainingWeight
    // summed across every charge this deposit's applications touched - mirrors PayableDto's
    // OutstandingChargeAmount, lets the DCC transaction list distinguish a deposit that fully
    // closed its charge(s) from one that only partially covered them.
    public decimal OutstandingChargeAmount { get; set; }

    public decimal OutstandingChargeWeight { get; set; }

    // Mirrors PayableDto's OrderCount - how many distinct orders a DEPOSIT's applications
    // touched, for the "거래 주문 수량" column.
    public int OrderCount { get; set; }

    // Mirrors PayableDto's IsMostRecentPayment - true only for a DEPOSIT row that has no
    // later (non-cancelled) DEPOSIT for the same retailer, since editing an older one after a
    // newer one already exists would invalidate later chronological ledger calculations.
    public bool IsMostRecentPayment { get; set; }
}

public class AppliedChargeDto
{

    public int ChargeId { get; set; }

    public int? OrderId { get; set; }

    public string? OrderNo { get; set; }

    public decimal AppliedAmount { get; set; }

    public decimal AppliedWeight { get; set; }

    public decimal ChargeAmount { get; set; }

    public decimal ChargeWeight { get; set; }

    // Live remaining balance on the charge itself, as of now - used the same way Payable's
    // chargeRemainingAmount/chargeRemainingWeight are: to tell "this application's own
    // weight/amount happened to be 0" apart from "nothing was actually owed".
    public decimal ChargeRemainingAmount { get; set; }

    public decimal ChargeRemainingWeight { get; set; }

    public List<ReceivableOrderItemSummaryDto> Items { get; set; } = new();
}

